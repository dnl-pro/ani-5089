// =============================================================================
//  Chapitre 7, exercice 6 — ce que la prédiction vous apporte.
//
//  Au démarrage, avant d'ouvrir la fenêtre : trois gestes de tête écrits en code,
//  échantillonnés comme un casque de 72 hertz (une pose par période), avec et sans
//  prédiction, comparés à la vraie pose de l'instant d'affichage (une période plus tard).
//  Chaque geste a la forme douce d'un geste réaliste : il s'accélère puis ralentit.
//    - rapide    : un quart de tour (90 degrés) en 400 ms,
//    - lent      : 45 degrés en 1000 ms,
//    - demi-tour : 180 degrés en 250 ms.
//  Chaque pose est NkQuatf::RotateY(NkAngle(lacet)) ; la vitesse d'une pose vient de la
//  pose précédente (VitesseAngulaire, celle du module de réalité virtuelle du moteur) ;
//  la pose montrée avec prédiction est Extrapoler(pose, vitesse, période). L'erreur est
//  l'angle, en degrés, avec la vraie pose de l'instant d'affichage. On moyenne pendant
//  le geste seulement (les poses échantillonnées de 0 à la durée du geste).
//  Une ligne par geste :
//      nom (A deg en D ms) : avec X deg, sans Y deg, rapport R
//  puis, pour comprendre, une ligne « detail » par geste.
//  MASALLE_EXIT=1 arrête la salle d'elle-même après une image.
//
//  (En-tête d'origine, étape 5 — la salle, en cubes, aux dimensions du chapitre 2.)
//
//  Toutes les dimensions sont en MÈTRES, et viennent du tableau du chapitre 7 :
//      sol 4 x 4, murs 2,5 de haut, porte 0,9 x 2,0,
//      deux fenêtres 1,2 x 1,0, table 1,2 x 0,8 avec le plateau à 0,75.
//
//  Le cube et la sphère de NkMeshSystem sont UNITAIRES, de demi-étendue 0,5 :
//  une échelle S donne donc une taille S, et poser un objet au sol demande de
//  le translater de S/2. Le plan de GetPlane() est unitaire LUI AUSSI, de
//  demi-étendue 0,5 : une échelle S y donne un côté S, et non un demi-côté.
// =============================================================================
